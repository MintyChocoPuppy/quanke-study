(() => {
 const params=new URLSearchParams(location.search);
 if(params.get('embed')==='1')document.body.classList.add('static-embedded');
 const filter=document.getElementById('noteFilter');
 filter?.addEventListener('input',()=>{const query=filter.value.trim().toLowerCase();for(const link of document.querySelectorAll('.static-note-link'))link.hidden=!link.dataset.title.includes(query);for(const section of document.querySelectorAll('.static-chapter'))section.hidden=![...section.querySelectorAll('.static-note-link')].some(link=>!link.hidden);});
 // Static deep links accept only filenames generated by the trusted exporter.
 if(params.get('id')&&/^[-a-zA-Z0-9]{1,160}$/.test(params.get('id')))location.replace('./'+params.get('id')+'.html'+(params.get('embed')==='1'?'?embed=1':'')+location.hash);
 if(params.get('embed')==='1')for(const a of document.querySelectorAll('.static-note-link,.static-pagination a'))a.searchParams?.set('embed','1');
})();
